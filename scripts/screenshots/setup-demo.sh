#!/usr/bin/env bash
# Build a demo directory of realistic fake files for App Store screenshots
# and the optional App Preview video walkthrough.
#
# Output: ~/Pictures/QuickRename-Demo/  (re-created each run)
#
#   Holiday/        — IMG_-prefixed photos (with real EXIF) + DSC_ mix
#   Meeting-notes/  — dd.mm.yy dated files + versioned drafts
#   Receipts/       — numbered files for the enumeration demo
#   Demo/           — single mixed folder for the video walkthrough:
#                     IMG_ photos, dated docs, and plain text files all
#                     side by side, so a 20–30s clip can flow through
#                     prefix-strip → regex date → EXIF → ⌘Z undo without
#                     restaging or switching folders.

set -euo pipefail

DEMO=~/Pictures/QuickRename-Demo
rm -rf "$DEMO"
mkdir -p "$DEMO"/{Holiday,Meeting-notes,Receipts,Demo}

# Source EXIF-bearing JPEGs (generated by scripts/generate-exif-fixtures.swift).
# If they don't exist yet, fall back to empty placeholders — EXIF demos will
# be no-ops but the rest of the workflow still works.
EXIF_SRC="$(pwd)/Tests/Fixtures/images/IMG_0001.jpg"

copy_jpg() {
  if [[ -f "$EXIF_SRC" ]]; then
    cp "$EXIF_SRC" "$1"
  else
    /usr/bin/printf '' > "$1"
  fi
}

# ── Holiday: messy IMG_-prefixed, DSC_ mixed in ──
for i in 0001 0002 0003 0004 0005 0006 0007 0008 0009 0010 0011 0012; do
  copy_jpg "$DEMO/Holiday/IMG_${i}.jpg"
done
for i in 100 101 102 103; do
  /usr/bin/printf '' > "$DEMO/Holiday/DSC_${i}.JPG"
done

# ── Meeting notes: dd.mm.yy dates, garbage prefixes, version drafts ──
for date in 14.03.26 21.03.26 28.03.26 04.04.26 11.04.26; do
  /usr/bin/printf '' > "$DEMO/Meeting-notes/garbage Meeting ${date}.pdf"
done
/usr/bin/printf '' > "$DEMO/Meeting-notes/Project Plan v1.docx"
/usr/bin/printf '' > "$DEMO/Meeting-notes/Project Plan v2 FINAL.docx"
/usr/bin/printf '' > "$DEMO/Meeting-notes/Project Plan v2 FINAL ACTUAL.docx"

# ── Receipts: numbered, upper-case .PDF for the lowercase-ext demo ──
for i in 1 2 3 4 5 6 7 8; do
  /usr/bin/printf '' > "$DEMO/Receipts/receipt-${i}.PDF"
done

# ── Demo: one folder with enough variety for the video walkthrough.
#    Suggested 25s narrative:
#      0–5s   Drop the folder. Empty preview.
#      5–10s  Search "IMG_" → 6 photos highlighted, others "unchanged".
#      10–15s Switch to Regex, search (\d{2})\.(\d{2})\.(\d{2}),
#             replace 20$3$2$1 → only the 3 dated PDFs highlighted.
#             Demonstrates that the engine intelligently scopes by pattern.
#      15–20s Toggle EXIF + Name-only, search ".+",
#             replace $CAMERA_MAKE-$DATE_TAKEN_YYYY...$ISO →
#             photos rename to camera-style, docs untouched.
#      20–25s Click Rename, then ⌘Z to undo.
#    The plain text files stay untouched the whole way through, which
#    visually reinforces the "rename only what matches" message. ──
for i in 01 02 03 04 05 06; do
  copy_jpg "$DEMO/Demo/IMG_${i}.jpg"
done
for date in 14.03.26 21.03.26 28.03.26; do
  /usr/bin/printf '' > "$DEMO/Demo/Meeting ${date}.pdf"
done
for name in "notes" "shopping list" "todo"; do
  /usr/bin/printf '' > "$DEMO/Demo/${name}.txt"
done

echo "Demo files written to $DEMO"
echo "Contents:"
ls -la "$DEMO"/*/ | grep -v "^total"
